/**
 * LATVIAN.
 *
 * The second language, and the first one the families this is built for
 * actually speak. English was never a neutral default here: a grandmother
 * invited into a family chronicle does not read "Coming up", and the person
 * the visibility controls exist to protect is exactly the person least likely
 * to read a foreign interface.
 *
 * Typed as `typeof strings`, so a key that is added to English and forgotten
 * here is a compile error rather than a blank label on somebody's screen.
 *
 * TWO THINGS TO KNOW WHEN EDITING:
 *
 *   1. COUNTING. Latvian does not have "one / many". A number ending in 1 -
 *      but not 11 - takes the singular: 1 komentārs, 21 komentārs, but 11
 *      komentāru. Zero takes the genitive plural: 0 komentāru. The helpers
 *      below do this once so no string has to remember it.
 *   2. TONE. The app addresses one person as "tu", the way a family does.
 *      "Jūs" would be a bank writing to a customer.
 */

/** A number ending in 1, but not 11: the form that takes the singular. */
function isSingular(n: number): boolean {
  return n % 10 === 1 && n % 100 !== 11;
}

/**
 * Latvian counting in one place: zero, the ...1 singular, and everything else.
 *
 * `plural` is the genitive used after 0 and after 11-19 ("nav komentāru"),
 * which is the form English has no equivalent of and the one that gets
 * forgotten.
 */
function count(n: number, singular: string, plural: string, genitive: string): string {
  if (n === 0) return `${n} ${genitive}`;
  return isSingular(n) ? `${n} ${singular}` : `${n} ${plural}`;
}

/**
 * "In" a family whose name nobody here can decline: "Tu jau esi Bergu ģimene"
 * says "you already are the Berg family". The usual name ends in "ģimene", and
 * that one word does decline - "Bergu ģimenē"; any other name is quoted after
 * the word itself: ģimenē "Ozoli".
 */
function inFamily(name: string): string {
  const trimmed = name.trim();
  return /ģimene$/i.test(trimmed) ? `${trimmed.slice(0, -1)}ē` : `ģimenē "${trimmed}"`;
}

